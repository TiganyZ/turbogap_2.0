   !! tg_allocate/tg_deallocate are the bare-array equivalents of tg_alloc/tg_dealloc,
   !! for cases where wrapping the array in a tg_array_<rank>_<prec> derived type
   !! (and updating every call site that reads it) isn't warranted. They avoid
   !! reallocation the same way, but since there is no wrapper type to remember the
   !! "used" extent separately from the physical one, callers see the full physical
   !! capacity via size(array) - there is no equivalent of used_dims here.


         subroutine tg_allocate_1_int (array,  dims, memory_total, memory_max, rank, name)
            character(len=*), intent(in) :: name
            integer, intent(in) :: rank
               integer, allocatable, intent(inout) :: array(:)
               real(dp), parameter :: size_type = 4.0_dp
            real(dp), intent(inout) :: memory_total
            real(dp), intent(inout) :: memory_max
            integer, intent(in) :: dims(1)
            integer :: sizes(1)
            integer, allocatable :: tmp(:)

            real(dp) :: total_array_size
            real(dp) :: prev_array_size

            total_array_size = real(dims(1),dp)*size_type

#ifdef _CHECK_ALLOCATE

            write (*, *) 'TGAllOC ', name, ' on rank ', rank, &
               ' size ', total_array_size, ' bytes, allocated? ', &
               allocated(array), ' current memory ', &
               memory_total/(1024.0_dp**2), ' Mb', &
               ' memory max ', memory_max, " bytes"

#endif

            if (allocated(array)) then
               ! Check the sizes currently to modify the memory
               sizes(1) = size( array, 1 )
               prev_array_size = real(sizes(1),dp)*size_type
               if (any(dims > sizes)) then
                  ! Grow into a new buffer, preserving overlapping data
                  allocate (tmp(1:dims(1)))
                  tmp(1:min(dims(1),sizes(1))) = array(1:min(dims(1),sizes(1)))
                  call move_alloc(tmp, array)

                  memory_total = memory_total - prev_array_size + total_array_size
                  memory_max = max(memory_total, memory_max)
               end if
               return
            end if

            allocate (array(1:dims(1)))

            memory_total = memory_total + total_array_size
            memory_max = max(memory_total, memory_max)

         end subroutine tg_allocate_1_int


