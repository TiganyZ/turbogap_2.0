   subroutine tg_print_memory(feature_name, total, max, rank)
      !! Optional per-feature memory report. Callers pass a memory_t's
      !! components directly, e.g. call tg_print_memory("neighbors", &
      !!    neighbors%memory%total, neighbors%memory%max, rank)
      character(len=*), intent(in) :: feature_name
      real(dp), intent(in) :: total
      real(dp), intent(in) :: max
      integer, intent(in) :: rank

      if (rank /= 0) return

      call print_parameter(trim(feature_name)//" mem (Mb)", total/(1024.0_dp**2))
      call print_parameter(trim(feature_name)//" mem max (Mb)", max/(1024.0_dp**2))

   end subroutine tg_print_memory

