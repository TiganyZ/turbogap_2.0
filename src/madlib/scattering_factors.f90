   function sinc(x) result(y)
      !! sin(x)/x, with the removable singularity at x = 0 handled via the
      !! leading Taylor term so callers don't need to special-case r = 0
      !! (e.g. the neighbor-list self entry).
      real(dp), intent(in) :: x
      real(dp) :: y

      if (abs(x) < 1.0e-8_dp) then
         y = 1.0_dp - x*x/6.0_dp
      else
         y = sin(x)/x
      end if
   end function sinc

   function dsinc(x) result(y)
      !! d/dx [sin(x)/x], same small-x handling as sinc.
      real(dp), intent(in) :: x
      real(dp) :: y

      if (abs(x) < 1.0e-8_dp) then
         y = -x/3.0_dp
      else
         y = (x*cos(x) - sin(x))/(x*x)
      end if
   end function dsinc

   subroutine get_scattering_factor(f, w, s)
      !! Waasmaier-Kirfel analytic form factor f(s) = c + sum_i a_i exp(-b_i s^2),
      !! s = sin(theta)/lambda = Q/(4 pi) in the "small q" = Q/(2 pi) convention
      !! used throughout this module (s = q/2).
      real(dp), intent(in)  :: w(9)
      real(dp), intent(in)  :: s
      real(dp), intent(out) :: f

      real(dp) :: s_sq
      integer :: j

      f = w(9)
      s_sq = s*s
      do j = 1, 4
         f = f + w(j)*exp(-w(j + 4)*s_sq)
      end do
   end subroutine get_scattering_factor

